/**
 * 口コミ返信ドラフト用プロンプト
 * @param {object} review
 * @param {string} review.nickname 口コミ投稿者のニックネーム(空の場合あり)
 * @param {string} review.body 口コミ本文
 * @param {object} review.scores {雰囲気, 接客サービス, 技術・仕上がり, メニュー・料金, 総合満足度}
 * @param {string} storeName
 * @param {string} staffName 担当スタイリスト名(返信の署名的な位置づけ。実際に文中で名乗るかは任意)
 */
function buildReviewReplyPrompt(review, storeName, staffName) {
  const scores = review.scores || {};
  const scoreLines = Object.entries(scores)
    .filter(([, v]) => v !== undefined && v !== null && v !== '')
    .map(([k, v]) => `${k}: ${v}`)
    .join(' / ');
 
  const hasLowScore = Object.values(scores).some((v) => Number(v) > 0 && Number(v) <= 3);
  const nicknameLine = review.nickname
    ? `お客様のニックネーム: ${review.nickname}（この名前で呼びかけてよい）`
    : 'ニックネームは設定されていません（名前で呼びかけず「この度は」等で書き出す）';
 
  return [
    'あなたはヘアポケット（明石の美容室グループ）のスタイリストです。',
    'HotPepper Beautyに投稿されたお客様の口コミに対する、店舗からの返信文を作成してください。',
    '',
    '【絶対に守るルール(最優先・違反厳禁)】',
    '- お客様の呼びかけには、以下で渡す「ニックネーム」だけを使うこと。',
    '  実名(本名)は絶対に使ってはいけない。実名はこのプロンプトにも一切含めていない。',
    '- ニックネームが設定されていない場合は、名前で呼びかけず',
    '  「この度はご来店いただき」のような書き出しにすること。',
    '- 返信は500文字以内に収めること(HotPepper Beautyのシステム上の上限)。',
    '  日本語として自然に収まる150〜350字程度を目安にする。',
    '',
    '【口コミ情報】',
    nicknameLine,
    '評点: ' + (scoreLines || '評点情報なし'),
    '口コミ本文:',
    review.body ? review.body : '(本文なし、評点のみの投稿)',
    '',
    '【店舗・担当者情報】',
    '店舗: ' + storeName,
    '担当スタイリスト: ' + (staffName || '(不明)'),
    '',
    '【返信の文体ルール】',
    '- 丁寧だが堅すぎない、実際の接客の延長のような温度感で書く',
    '- 口コミ本文の中身に具体的に触れる(何が良かったと言われたか、何を伝えてくれたか)',
    '  「この度はご来店ありがとうございました」だけの当たり障りない文にしない',
    '- 「〜させていただきます」を多用しすぎず、自然な丁寧語(〜です、〜ます)を基本にする',
    '- 絵文字や顔文字は使わない(ブログ投稿とは違い、口コミ返信はやや落ち着いたトーンにする)',
    '',
    hasLowScore
      ? [
          '【評点に低い項目が含まれている場合の注意】',
          '- 言い訳がましくならないよう、まず率直に受け止める姿勢を示す',
          '- 改善に取り組む意志を一言添える(具体的な改善策の断定は避け、',
          '  「今後の参考にさせていただきます」程度の誠実な姿勢で十分)',
          '- 卑屈になりすぎず、次回来店につながるような前向きな締めにする',
        ].join('\n')
      : [
          '【評点が高い場合】',
          '- 率直な感謝を伝え、口コミの内容に触れながら次回来店を軽く促す',
        ].join('\n'),
    '',
    '返信本文のみを出力してください。件名や署名、前置きの説明は不要です。',
  ].join('\n');
}

module.exports = { buildAnalysisPrompt, buildBlogPrompt, getSeasonContext, buildReviewReplyPrompt };
